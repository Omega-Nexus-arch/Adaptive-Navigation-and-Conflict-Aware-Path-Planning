SlopeCostModel::SlopeCostModel(const Options & options)
: options_(options) {}

SlopeSample SlopeCostModel::SampleSlope(const ElevationMap & map, double x, double y) const
{
  SlopeSample sample;
  if (map.Empty()) {
    return sample;
  }

  // Difference from the containing cell's centre, not from the raw query
  // point. Probing `x + resolution` from an arbitrary x is unsafe in floating
  // point: when x sits near a cell boundary the probe can round back into the
  // same cell, the stencil collapses from two cells to one, and the measured
  // gradient comes out at half its true value. That failure is silent, and it
  // under-reports exactly the steep slopes the lethal threshold exists to
  // catch. From a cell centre, +/- one resolution always lands in the
  // neighbouring cell.
  double sample_x = x;
  double sample_y = y;
  if (!map.CellCentre(x, y, &sample_x, &sample_y)) {
    return sample;   // Outside the map; caller applies the unknown policy.
  }

  const double step = map.resolution;
  const double centre = map.HeightAt(sample_x, sample_y);

  // Central differences. A forward difference would bias the computed slope
  // half a cell downhill and move the lethal boundary of a steep ramp by a
  // couple of centimetres.
  const double dz_dx =
    (map.HeightAt(sample_x + step, sample_y, centre) -
    map.HeightAt(sample_x - step, sample_y, centre)) / (2.0 * step);
  const double dz_dy =
    (map.HeightAt(sample_x, sample_y + step, centre) -
    map.HeightAt(sample_x, sample_y - step, centre)) / (2.0 * step);

  sample.gradient = std::hypot(dz_dx, dz_dy);
  sample.angle = std::atan(sample.gradient);
  sample.valid = true;
  return sample;
}

std::uint8_t SlopeCostModel::CostForAngle(double angle) const
{
  const double magnitude = std::abs(angle);

  if (magnitude <= options_.free_angle) {
    return kFree;
  }
  if (magnitude >= options_.max_traversable_angle) {
    // Beyond what the drive train can climb. Not expensive: impassable.
    return kLethal;
  }

  const double span = options_.max_traversable_angle - options_.free_angle;
  if (span <= 1e-9) {
    return kLethal;
  }
  const double fraction = (magnitude - options_.free_angle) / span;
  const double shaped = std::pow(std::min(1.0, std::max(0.0, fraction)), options_.curve_exponent);

  const double base = static_cast<double>(options_.base_cost);
  const double top = static_cast<double>(options_.max_cost);
  const double cost = base + (top - base) * shaped;

  // Clamp below LETHAL. A traversable slope priced at 254 would be refused
  // outright rather than merely avoided, which breaks the "ramps are used when
  // they are the only viable path" half of the requirement.
  return static_cast<std::uint8_t>(
    std::min(static_cast<double>(kLethal - 1), std::max(0.0, cost)));
}

std::uint8_t SlopeCostModel::CostAt(const ElevationMap & map, double x, double y) const
{
  const SlopeSample sample = SampleSlope(map, x, y);
  if (!sample.valid) {
    return options_.unknown_is_free ? kFree : kNoInformation;
  }
  return CostForAngle(sample.angle);
}

