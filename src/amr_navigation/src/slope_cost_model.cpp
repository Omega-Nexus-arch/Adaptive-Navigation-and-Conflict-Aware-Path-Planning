double ElevationMap::HeightAt(double x, double y, double fallback) const
{
  if (Empty() || resolution <= 0.0) {
    return fallback;
  }
  const int column = static_cast<int>(std::floor((x - origin_x) / resolution));
  // Row 0 is maximum y, so the row index counts down from the top edge.
  const double y_max = origin_y + static_cast<double>(height) * resolution;
  const int row = static_cast<int>(std::floor((y_max - y) / resolution));

  if (column < 0 || row < 0 || column >= static_cast<int>(width) ||
    row >= static_cast<int>(height))
  {
    return fallback;
  }
  return heights[Index(static_cast<std::uint32_t>(column), static_cast<std::uint32_t>(row))];
}

bool ElevationMap::CellCentre(double x, double y, double * centre_x, double * centre_y) const
{
  if (Empty() || resolution <= 0.0) {
    return false;
  }
  const int column = static_cast<int>(std::floor((x - origin_x) / resolution));
  const double y_max = origin_y + static_cast<double>(height) * resolution;
  const int row = static_cast<int>(std::floor((y_max - y) / resolution));

  if (column < 0 || row < 0 || column >= static_cast<int>(width) ||
    row >= static_cast<int>(height))
  {
    return false;
  }
  *centre_x = origin_x + (static_cast<double>(column) + 0.5) * resolution;
  *centre_y = y_max - (static_cast<double>(row) + 0.5) * resolution;
  return true;
}

ElevationMap ElevationMap::FromFiles(const std::string & yaml_path)
{
  std::string image_name;
  if (!ReadScalar(yaml_path, "image", &image_name)) {
    throw std::runtime_error("elevation metadata '" + yaml_path + "' has no 'image'");
  }

  // Resolve the image relative to the metadata file.
  std::string image_path = image_name;
  if (!image_name.empty() && image_name.front() != '/') {
    const std::size_t slash = yaml_path.find_last_of('/');
    if (slash != std::string::npos) {
      image_path = yaml_path.substr(0, slash + 1) + image_name;
    }
  }

  ElevationMap map;
  map.resolution = ReadRequiredDouble(yaml_path, "resolution");
  const double elevation_min = ReadRequiredDouble(yaml_path, "elevation_min");
  const double elevation_max = ReadRequiredDouble(yaml_path, "elevation_max");

  std::string origin_text;
  if (!ReadScalar(yaml_path, "origin", &origin_text)) {
    throw std::runtime_error("elevation metadata '" + yaml_path + "' has no 'origin'");
  }
  // origin: [x, y, yaw]
  std::replace(origin_text.begin(), origin_text.end(), '[', ' ');
  std::replace(origin_text.begin(), origin_text.end(), ']', ' ');
  std::replace(origin_text.begin(), origin_text.end(), ',', ' ');
  std::istringstream origin_stream(origin_text);
  origin_stream >> map.origin_x >> map.origin_y;

  const std::vector<std::uint8_t> pixels = ReadPgm(image_path, &map.width, &map.height);
  const double span = elevation_max - elevation_min;
  map.heights.resize(pixels.size());
  for (std::size_t i = 0; i < pixels.size(); ++i) {
    map.heights[i] = elevation_min + static_cast<double>(pixels[i]) * span / 255.0;
  }
  return map;
}

