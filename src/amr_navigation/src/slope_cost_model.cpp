/// \brief Minimal PGM (P5, 8-bit binary) reader.
///
/// Deliberately hand-rolled rather than pulling in an image library: the
/// format is a dozen lines, and this avoids making the navigation stack depend
/// on OpenCV purely to read a height field.
std::vector<std::uint8_t> ReadPgm(
  const std::string & path, std::uint32_t * width, std::uint32_t * height)
{
  std::ifstream file(path, std::ios::binary);
  if (!file) {
    throw std::runtime_error("cannot open elevation image '" + path + "'");
  }

  std::string magic;
  file >> magic;
  if (magic != "P5") {
    throw std::runtime_error(
            "elevation image '" + path + "' is '" + magic + "', expected binary PGM (P5)");
  }

  // PGM allows comments anywhere in the header.
  auto read_value = [&file]() {
      int value = 0;
      while (file >> std::ws, file.peek() == '#') {
        std::string comment;
        std::getline(file, comment);
      }
      file >> value;
      return value;
    };

  const int parsed_width = read_value();
  const int parsed_height = read_value();
  const int max_value = read_value();
  if (parsed_width <= 0 || parsed_height <= 0 || max_value != 255) {
    throw std::runtime_error("elevation image '" + path + "' has an unsupported header");
  }
  file.get();   // Consume the single whitespace byte before the raster.

  const std::size_t count =
    static_cast<std::size_t>(parsed_width) * static_cast<std::size_t>(parsed_height);
  std::vector<std::uint8_t> pixels(count);
  file.read(reinterpret_cast<char *>(pixels.data()), static_cast<std::streamsize>(count));
  if (static_cast<std::size_t>(file.gcount()) != count) {
    throw std::runtime_error(
            "elevation image '" + path + "' is truncated: expected " + std::to_string(count) +
            " bytes, got " + std::to_string(file.gcount()));
  }

  *width = static_cast<std::uint32_t>(parsed_width);
  *height = static_cast<std::uint32_t>(parsed_height);
  return pixels;
}

/// \brief Pull `key: value` out of a flat YAML file.
///
/// The metadata file is generated by this project and has a fixed, flat shape,
/// so a line scan is sufficient and keeps yaml-cpp out of the costmap plugin's
/// link line.
bool ReadScalar(const std::string & path, const std::string & key, std::string * value)
{
  std::ifstream file(path);
  if (!file) {
    return false;
  }
  std::string line;
  while (std::getline(file, line)) {
    const std::size_t comment = line.find('#');
    if (comment != std::string::npos) {
      line = line.substr(0, comment);
    }
    const std::size_t colon = line.find(':');
    if (colon == std::string::npos) {
      continue;
    }
    std::string found = line.substr(0, colon);
    found.erase(0, found.find_first_not_of(" \t"));
    found.erase(found.find_last_not_of(" \t") + 1);
    if (found != key) {
      continue;
    }
    std::string rest = line.substr(colon + 1);
    rest.erase(0, rest.find_first_not_of(" \t"));
    rest.erase(rest.find_last_not_of(" \t\r") + 1);
    *value = rest;
    return true;
  }
  return false;
}

double ReadRequiredDouble(const std::string & path, const std::string & key)
{
  std::string text;
  if (!ReadScalar(path, key, &text)) {
    throw std::runtime_error("elevation metadata '" + path + "' has no '" + key + "'");
  }
  return std::stod(text);
}

